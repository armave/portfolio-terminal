import type { PortfolioTransactionEventType, CashflowCategory } from '../types/portfolioTransaction';

export interface CashflowClassificationInput {
  type?: unknown;
  description?: unknown;
  category?: unknown;
  typeCode?: unknown;
  typeCodeName?: unknown;
  raw?: Record<string, unknown> | Record<string, string>;
}

export interface CashflowClassification {
  category: CashflowCategory;
  eventType: PortfolioTransactionEventType | null;
  classified: boolean;
}

function normalizeText(value: unknown): string {
  return (typeof value === 'string' || typeof value === 'number' ? String(value) : '')
    .toLowerCase().replace(/[_-]+/g, ' ').replace(/\s+/g, ' ').trim();
}

function sourceText(input: CashflowClassificationInput): string {
  const raw = input.raw || {};
  // Only use the provider's explicit transaction label. Unrelated raw fields
  // (balance snapshots, account metadata, rate notes) must not override it.
  return [
    input.type,
    input.description,
    input.category,
    input.typeCodeName,
    raw.type_code_name,
    raw.typeCodeName
  ].map(normalizeText).filter(Boolean).join(' ');
}

function providerCodeClassification(input: CashflowClassificationInput): CashflowClassification | null {
  const raw = input.raw || {};
  const code = normalizeText(input.typeCode ?? raw.type_code ?? raw.typeCode).replace(/\s+/g, '_');
  if (!code) return null;

  if (
    code.startsWith('commission_') ||
    ['commission', 'icc_commission', 'card_commission', 'agent_fee', 'agent_fee_reverted',
      'agent_fee_annual', 'agent_fee_annual_reverted', 'commission_rebates', 'commission_refund',
      'recurrent_subscription'].includes(code)
  ) return { category: 'commission', eventType: 'fee', classified: true };

  if (code.startsWith('tax_') || code === 'tax')
    return { category: 'tax', eventType: 'fee', classified: true };

  if (code === 'percents')
    return { category: 'interest_income', eventType: 'interest.income', classified: true };

  if (['dividend', 'dividend_compensation'].includes(code))
    return { category: 'dividend', eventType: 'dividend', classified: true };

  if (code === 'coupon')
    return { category: 'interest_income', eventType: 'interest.income', classified: true };

  // Trade settlement rows are the signed cash legs generated by executions.
  // They are not income/cost adjustments or external portfolio contributions.
  if (['trade', 'dvp', 'otc_trade', 'trade_cancellation'].includes(code))
    return { category: 'trade', eventType: null, classified: true };

  // Order blocks and releases describe reserved buying power, not settled cash.
  if (['block', 'unblock', 'block_commission', 'unblock_commission', 'pending_card_authorisation'].includes(code))
    return { category: 'order_reservation', eventType: null, classified: true };

  if (['storn_correction', 'conversion_reverted', 'merger_reverted', 'spin_off_reverted',
    'split_reverted', 'dividend_reverted', 'coupon_reverted', 'tax_reverted', 'tax_vat_refund'].includes(code))
    return { category: 'correction', eventType: 'cash.adjustment', classified: true };

  if (['merger', 'spin_off', 'split', 'rights_distribution', 'corporate_action_compensation',
    'corporate_action_compensation_reverted', 'stock_dividend', 'stock_dividend_compensation',
    'stock_dividend_compensation_reverted'].includes(code))
    return { category: 'corporate_action', eventType: 'corporate-action', classified: true };

  if (['intercompany', 'internal_holding'].includes(code))
    return { category: 'transfer', eventType: 'cash.transfer', classified: true };

  return null;
}

/** Shared fail-closed classifier for broker import, reconciliation and reporting. */
export function classifyCashflow(input: CashflowClassificationInput): CashflowClassification {
  const providerClassification = providerCodeClassification(input);
  if (providerClassification) return providerClassification;

  const value = sourceText(input);
  const has = (pattern: RegExp) => pattern.test(value);
  if (!value) return { category: 'unclassified', eventType: null, classified: false };

  // Older persisted rows may retain the provider's TRADE-{id}-{currency}
  // label but predate type_code persistence. Require this exact structured
  // label; do not infer a trade from arbitrary prose mentioning trading.
  const normalizedType = normalizeText(input.type);
  if (/^trade(?: \d+)?(?: [a-z]{3})?$/.test(normalizedType))
    return { category: 'trade', eventType: null, classified: true };

  if (has(/\b(dividend reinvestment|reinvested distribution|reinvestment of dividend)\b/))
    return { category: 'unclassified', eventType: null, classified: false };
  // Explicit corporate-action tax descriptions are cash taxes, not generic
  // non-cash corporate-action audit events. Keep this narrow and ahead of the
  // broader corporate-action wording so only an explicit tax label gains a
  // settled cash direction.
  if (has(/\bcorporate action tax\b/))
    return { category: 'tax', eventType: 'fee', classified: true };
  if (has(/\b(stock split|reverse split|merger|spin off|reorganization|reorganisation|corporate action|symbol change|cash in lieu)\b/))
    return { category: 'corporate_action', eventType: 'corporate-action', classified: true };
  if (has(/\b(withholding tax|tax withheld|tax|vat)\b/))
    return { category: 'tax', eventType: 'fee', classified: true };
  if (has(/\b(correction|corrected|reversal|reversed)\b/))
    return { category: 'correction', eventType: 'cash.adjustment', classified: true };
  if (has(/\b(adjustment|balance adjustment)\b/)) {
    if (has(/\bmargin\b/)) return { category: 'unclassified', eventType: null, classified: false };
    return { category: 'adjustment', eventType: 'cash.adjustment', classified: true };
  }
  if (has(/\b(deposit|funding|funded|credit to account)\b/))
    return { category: 'deposit', eventType: 'cash.deposit', classified: true };
  if (has(/\b(withdrawal|withdraw|debit from account)\b/))
    return { category: 'withdrawal', eventType: 'cash.withdrawal', classified: true };
  if (has(/\b(transfer|wire|internal transfer)\b/))
    return { category: 'transfer', eventType: 'cash.transfer', classified: true };
  if (has(/\b(interest income|interest received|interest credited|credited interest|credit interest|bank interest)\b/))
    return { category: 'interest_income', eventType: 'interest.income', classified: true };
  // TradeNet describes negative-cash-balance charges as fees/commissions,
  // not as financing interest. Keep them distinct from margin-interest rows.
  if (has(/\b(fee|commission|charge)\b.{0,80}\bnegative cash balance\b|\bnegative cash balance\b.{0,80}\b(fee|commission|charge)\b/)) {
    return has(/\bcommission\b/)
      ? { category: 'commission', eventType: 'fee', classified: true }
      : { category: 'fee', eventType: 'fee', classified: true };
  }
  const hasExplicitReservationLabel = [input.type, input.description]
    .map(normalizeText)
    .some(label =>
      ['block', 'unblock', 'block commission', 'unblock commission'].includes(label) ||
      /^debiting funds under order #?\d+$/.test(label) ||
      /^crediting funds under order #?\d+$/.test(label) ||
      /^funds (?:blocked|unblocked) under order #?\d+$/.test(label) ||
      /^(?:block|unblock)\b.{0,120}\b(order|funds)\b/.test(label)
    );
  if (hasExplicitReservationLabel)
    return { category: 'order_reservation', eventType: null, classified: true };
  if (has(/\b(margin interest|margin fee|financing|borrow fee)\b/))
    return { category: 'margin_interest', eventType: 'margin.interest', classified: true };
  if (has(/\bmargin\b/))
    return { category: 'unclassified', eventType: null, classified: false };
  if (has(/\b(dividends?|distributions?|coupon)\b/))
    return { category: 'dividend', eventType: 'dividend', classified: true };
  if (has(/\bcommission\b/))
    return { category: 'commission', eventType: 'fee', classified: true };
  if (has(/\b(fee|charge|service cost)\b/))
    return { category: 'fee', eventType: 'fee', classified: true };
  return { category: 'unclassified', eventType: null, classified: false };
}

/** True only when the source category carries a safely interpretable account-cash direction. */
export function hasKnownCashflowDirection(category: CashflowCategory): boolean {
  return [
    'deposit', 'withdrawal', 'dividend', 'interest_income',
    'commission', 'fee', 'tax', 'margin_interest', 'trade', 'transfer'
  ].includes(category);
}

/** Signed account movement; charge refunds reverse the normal outflow sign. */
export function normalizeClassifiedCashflowAmount(category: CashflowCategory, amount: number, description = ''): number {
  if (!Number.isFinite(amount)) return amount;
  if (category === 'deposit' || category === 'dividend' || category === 'interest_income') return Math.abs(amount);
  if (category === 'withdrawal') return -Math.abs(amount);
  if (category === 'fee' || category === 'commission' || category === 'tax' || category === 'margin_interest') {
    const normalizedDescription = description.toLowerCase().replace(/[_-]+/g, ' ');
    return /\b(refund|rebate|reimbursement)\b/.test(normalizedDescription) ? Math.abs(amount) : -Math.abs(amount);
  }
  return amount;
}
